#!/usr/bin/env python3
"""
Keeps the bitmap cache lists of the views in sync with Project_GatewayTFT.touchgfx.

Compressed images (L8 RLE/LZW) are only drawn when they are decompressed into the RAM
bitmap cache first. Every *View.cpp calls decompressBitmaps() with the images of its screen.
Run this after adding/changing images or screens in TouchGFX Designer (then Generate Code):

    python tools/update_bitmap_lists.py

It rewrites the block between '// BEGIN bitmap list' and '// END bitmap list' in each view,
adds the block (and Bitmap::clearCache()) to views that do not have it yet, and sets the size of
the cache (FrontendApplication.cpp) to the largest screen + margin.
"""
import json, os, re, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = os.path.join(ROOT, "assets", "images")
CLUT = 1024          # L8_ARGB8888 palette
MARGIN = 1.15


def bid(f):
    return "BITMAP_" + re.sub(r"[^A-Za-z0-9]", "_", f[:-4]).upper() + "_ID"


def png_size(f):
    with open(os.path.join(IMG, f), "rb") as fh:
        h = fh.read(24)
    return struct.unpack(">II", h[16:24])


def read(p):
    raw = open(p, encoding="utf8", newline="").read()
    return raw.replace("\r\n", "\n"), ("\r\n" if "\r\n" in raw else "\n")


def write(p, t, nl):
    new = t.replace("\n", nl)
    if os.path.exists(p) and open(p, encoding="utf8", newline="").read() == new:
        return  # unchanged: keep the timestamp, no needless rebuild
    open(p, "w", encoding="utf8", newline="").write(new)


def main():
    proj = json.load(open(os.path.join(ROOT, "Project_GatewayTFT.touchgfx"), encoding="utf8"))
    biggest = 0
    for s in proj["Application"]["Screens"]:
        name = s["Name"]
        files = []
        for c in s["Components"]:
            for k in ("RelativeFilename", "Pressed", "Released"):
                f = c.get(k)
                if f and f not in files and os.path.exists(os.path.join(IMG, f)):
                    files.append(f)
        if not files:
            continue
        size = sum(w * h + CLUT for w, h in map(png_size, files))
        biggest = max(biggest, size)
        p = os.path.join(ROOT, "gui", "src", f"{name.lower()}_screen", f"{name}View.cpp")
        if not os.path.exists(p):
            print("skip (no view file):", p); continue
        t, nl = read(p)
        lst = ",\n        ".join(bid(f) for f in files)
        block = (f"    // BEGIN bitmap list (generated by tools/update_bitmap_lists.py)\n"
                 f"    static const touchgfx::BitmapId ids[] = {{\n        {lst}\n    }};\n"
                 f"    decompressBitmaps(ids);\n    // END bitmap list")
        if "// BEGIN bitmap list" in t:
            t = re.sub(r"    // BEGIN bitmap list.*?// END bitmap list", lambda m: block, t, flags=re.S)
        else:
            t = re.sub(r"\n    // compressed images to RAM \(bitmap cache\)\n    static const.*?decompressBitmaps\(ids\);", "", t, flags=re.S)
            t = t.replace(f"    {name}ViewBase::setupScreen();", f"    {name}ViewBase::setupScreen();\n\n{block}", 1)
        if "BitmapCache.hpp" not in t:
            t = t.replace(f"#include <gui/{name.lower()}_screen/{name}View.hpp>",
                          f"#include <gui/{name.lower()}_screen/{name}View.hpp>\n#include <gui/common/BitmapCache.hpp>\n#include <images/BitmapDatabase.hpp>", 1)
        if "clearCache" not in t:
            t = t.replace(f"    {name}ViewBase::tearDownScreen();", f"    {name}ViewBase::tearDownScreen();\n    touchgfx::Bitmap::clearCache();", 1)
        write(p, t, nl)
        print(f"{name:10s} {len(files):2d} images, {size/1024:6.1f} KB")

    # cache size
    p = os.path.join(ROOT, "gui", "src", "common", "FrontendApplication.cpp")
    t, nl = read(p)
    kb = int(-(-biggest * MARGIN // 1024))
    t2 = re.sub(r"bitmapCache\[\d+ \* 1024 / 2\]", f"bitmapCache[{kb} * 1024 / 2]", t)
    if t2 != t:
        write(p, t2, nl)
    print(f"bitmap cache: {kb} KB (largest screen {biggest/1024:.1f} KB)")


if __name__ == "__main__":
    sys.exit(main())
